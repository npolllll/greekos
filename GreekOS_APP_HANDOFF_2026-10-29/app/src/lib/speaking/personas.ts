/**
 * Who the AI interlocutor is in each corpus scenario (the scenarios define stages and lines, not the
 * persona's role). Engine configuration written by the developer from each scenario's opening line
 * and learner brief; it is not course content and changes nothing in the corpus.
 */
export interface SceneRole {
  /** The persona's role in the scene (Russian, for the prompt). */
  persona: string;
  /** The learner's role. */
  learner: string;
  /** Address form the persona uses. */
  register: 'εσείς' | 'εσύ';
  /** A name the scenario itself gives the persona (used when the voice presentation matches). */
  name?: { el: string; presentation: 'female' | 'male' };
}

